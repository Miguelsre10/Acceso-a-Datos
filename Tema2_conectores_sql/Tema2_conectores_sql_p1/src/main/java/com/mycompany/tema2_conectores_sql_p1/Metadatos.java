    public void ShowMetadata() {
        final String server = "jdbc:mysql://localhost:3306/";
        final String user = "root";
        final String pass = "root";
        try {
            Connection conn = DriverManager.getConnection(server, user, pass);
            if (conn != null) {
                System.out.println("Conexion realizada.");

                DatabaseMetaData metadatos = conn.getMetaData();
                jTF_nombreSgbd.setText(metadatos.getDatabaseProductName());
                jTF_versionSgbd.setText(metadatos.getDatabaseProductVersion());
                jTF_nombreDriver.setText(metadatos.getDriverName());
                jTF_versionDriver.setText(metadatos.getDriverVersion());
                jTF_usuario.setText(metadatos.getUserName());
                
                conn.close();
            }
        } catch (Exception e) {
            System.err.println(e.getMessage());
        }
    }
