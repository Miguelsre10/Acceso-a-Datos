    public void ShowPrimerAlumno() {
        String server = "jdbc:mysql://localhost:3306/instituto";
        String user = "root";
        String pass = "root";
        String consultasql = "select * from alumnos;";
        try {
            conn = DriverManager.getConnection(server, user, pass);
            if (conn != null) {
                System.out.println("Conexion realizada.");
                ps = conn.prepareStatement(consultasql,
                        ResultSet.TYPE_SCROLL_INSENSITIVE, ResultSet.CONCUR_READ_ONLY);

                rs = ps.executeQuery();

                if (rs.first()) {
                    ShowAlumno(rs);
                }

            }
        } catch (Exception e) {
            System.err.println(e.getMessage());
        }
    }

    private void ShowAlumno(ResultSet rs) {
        try {
            setIdAlumno(rs.getString(1));
            setNombreAlumno(rs.getString(2));
            setMediaAlumno(rs.getFloat(3));
        } catch (SQLException ex) {
            System.getLogger(CRUD_Alumnos.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
        }
    }
